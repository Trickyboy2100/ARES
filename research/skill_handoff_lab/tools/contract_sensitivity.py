"""Offline input sensitivity, explicitly NOT a new physical outcome.

Saved v19 observations are post-command observations, not claimed to reproduce
the same row's pre-command raw action. Contracts permute within measured data.
"""
import argparse,json,hashlib
from pathlib import Path
import numpy as np
import torch
from stable_baselines3 import PPO
p=argparse.ArgumentParser();p.add_argument('--model',type=Path,required=True);p.add_argument('--audit',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
torch.set_num_threads(2);rows=json.loads(a.audit.read_text())
obs=np.concatenate([np.asarray(r['policy_observation'],dtype=np.float32) for r in rows[::4]])
contracts=np.concatenate([np.asarray(r['executed_contract'],dtype=np.float32) for r in rows[::4]])
model=PPO.load(a.model,device='cpu');permutation=np.random.default_rng(0).permutation(len(obs))
swapped=obs.copy();swapped[:,25:]=obs[permutation,25:]
with torch.no_grad():
    original=model.policy.get_distribution(torch.as_tensor(obs)).distribution.mean.numpy()
    alternate=model.policy.get_distribution(torch.as_tensor(swapped)).distribution.mean.numpy()
variation=np.ptp(contracts,axis=0)
result={'evidence_level':'OFFLINE_NETWORK_SENSITIVITY_NOT_PHYSICAL_GENERALIZATION',
    'observation_phase':'saved post-command physical-state observation; not exact input for logged raw action',
    'samples':len(obs),'contract_fields_with_nonzero_observed_range':np.where(variation>1e-7)[0].tolist(),
    'contract_field_ranges':variation.tolist(),'mean_abs_raw_action_change':np.abs(original-alternate).mean(0).tolist(),
    'max_abs_raw_action_change':np.abs(original-alternate).max(0).tolist(),
    'limitations':['contract permutation can create incoherent counterfactual conditions',
        'sensitivity is not evidence of learned semantic use or performance advantage',
        'no simulated episodes or success labels are generated by this diagnostic'],
    'model_sha256':hashlib.sha256(a.model.read_bytes()).hexdigest(),'audit_sha256':hashlib.sha256(a.audit.read_bytes()).hexdigest()}
a.output.write_text(json.dumps(result,indent=2));print(json.dumps(result,indent=2))
